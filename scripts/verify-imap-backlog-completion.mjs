import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fixture, root } from './imap-backlog-fixture.mjs'

const f = await fixture()
const options = { scope: 'inbox', protect_flagged: true, selected: null }
const checks = []
const wires = async () => (await readFile(join(f.directory, 'move-wire-exact.jsonl'), 'utf8').catch(() => '')).trim().split('\n').filter(Boolean).map(JSON.parse)
const resolutions = evidence => Object.fromEntries(Object.keys(evidence.intent.messages).map(uid => [uid, evidence.readback && evidence.mapping.kind === 'validated' && evidence.mapping.mapping.pairs[uid] ? 'mapped' : 'unmapped']))
async function record(name, extra = {}) {
  checks.push({ name, directory: f.directory, passed: true, ...extra })
  await writeFile(join(root, '.audit/imap-backlog-workflow-completion-http-results.json'), JSON.stringify({ checks }, null, 2))
}
try {
  await f.start(true); await f.savedWorkspace(true)
  const preview = await f.command('preview', { options })
  const before = await f.observe()
  await writeFile(join(f.directory, 'move-mode'), 'partial')
  await f.command('confirm', { options, receipt: preview.receipt, confirmed: true })
  assert.equal((await f.terminal()).progress.state, 'failed')
  await writeFile(join(f.directory, 'move-mode'), '')
  const forward = await f.observe()
  const run = forward.journal.runs.at(-1)
  assert.equal(run.status, 'uncertain')
  assert.deepEqual(resolutions(run.batches[0]), { 4: 'mapped', 8: 'unmapped', 19: 'unmapped' })
  assert.deepEqual(forward.folders.INBOX.uids, [8, 19, 99])
  assert.deepEqual(forward.folders['Personal/Studio'].uids, [40, 60])
  assert.equal(forward.independent, before.independent)
  assert.deepEqual(forward.uid_next, { ...before.uid_next, 'Personal/Studio': before.uid_next['Personal/Studio'] + 4 })
  await f.stop('SIGKILL'); await f.start()
  await f.observe('later_flag')
  const flagged = await f.observe()
  await f.command('reconcile', { run: run.id })
  const reconciled = await f.observe()
  await f.command('reconcile', { run: run.id })
  const repeated = await f.observe()
  assert.equal(repeated.revision, reconciled.revision)
  assert.deepEqual(repeated.journal, reconciled.journal)
  assert.deepEqual(reconciled.journal.runs.at(-1).batches, run.batches)
  assert.equal(reconciled.journal.runs.at(-1).status, 'uncertain')
  await f.command('resume', { run: run.id }); await f.terminal()
  assert.equal((await wires()).length, 1)
  await f.command('preview', { options }, 422)
  const undo = await f.command('undo_preview', { run: run.id })
  assert.equal(undo.reverse.length, 1)
  assert.deepEqual(Object.keys(undo.reverse[0].evidence.intent.messages), ['60'])
  assert.equal(undo.conflicts, 2)
  await f.command('undo', { run: run.id, receipt: undo.receipt, confirmed: false })
  assert.equal((await f.terminal()).progress.state, 'failed')
  assert.equal((await f.observe()).journal.runs.at(-1).undo_receipt, null)
  await f.command('undo', { run: run.id, receipt: undo.receipt, confirmed: true })
  assert.equal((await f.terminal()).progress.state, 'complete')
  const undone = await f.observe()
  const reversed = undone.journal.runs.at(-1)
  assert.equal(reversed.status, 'undone')
  assert.equal(reversed.undo_conflicts, 2)
  assert.deepEqual(reversed.batches, run.batches)
  assert.deepEqual(undone.folders.INBOX.uids, [8, 19, 99, 104])
  assert.ok(undone.folders.INBOX.messages['104'].flags.includes('$later-client'))
  assert.deepEqual(undone.folders['Personal/Studio'].uids, [40])
  assert.equal(undone.independent, before.independent)
  assert.equal(undone.unrelated, before.unrelated)
  assert.deepEqual(undone.uid_next, { ...flagged.uid_next, INBOX: flagged.uid_next.INBOX + 4 })
  assert.deepEqual((await wires()).map(w => w.command), ['UID MOVE 4,8,19 "Personal/Studio"', 'UID MOVE 60 "INBOX"'])
  await f.stop('SIGKILL'); await f.start()
  const reopened = (await f.command('status')).journal.runs.at(-1)
  assert.equal(reopened.status, 'undone')
  await f.command('undo_preview', { run: run.id }, 422)
  await f.command('resume_undo', { run: run.id }); await f.terminal()
  await f.command('resume', { run: run.id }); await f.terminal()
  await f.command('preview', { options }, 422)
  assert.equal((await wires()).length, 2)
  const final = await f.observe()
  assert.deepEqual(final.folders, undone.folders)
  assert.equal(final.independent, before.independent)
  await record('partial-NO-subset-undo-after-replacement-observe-only-reconcile-no-retry')
  await f.close()
  console.log(`Passed ${checks.length} saved protocol completion groups`)
} finally { await f.close() }
