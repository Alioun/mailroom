import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
const artifacts = fileURLToPath(new URL('../../.audit/rules-browser/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    window.rulesCspViolations = []
    document.addEventListener('securitypolicyviolation', event => window.rulesCspViolations.push(event.violatedDirective))
  })
  await page.goto('http://127.0.0.1:4173')
  const section = page.getByRole('region', { name: 'Rules and proof', exact: true })
  const run = section.getByRole('button', { name: 'Run sample preview', exact: true })
  await run.click()
  await section.getByText('3 messages receive copies. 2 need recipient review.', { exact: true }).waitFor()
  assert.equal(await section.locator('.decision').count(), 14)
  await section.getByText('forward.keywords · Keyword forward requires nonbulk mail and PDF/XML attachment evidence. Header census has no attachment evidence; whole rule omitted', { exact: true }).waitFor()
  await section.getByText('Compiled artifact', { exact: true }).click()
  const artifactId = await section.locator('.artifact-id').innerText()
  assert.match(artifactId, /[0-9a-f]{64}/)
  await page.screenshot({ path: `${artifacts}/sieve-proof.png`, fullPage: true })
  await section.getByLabel('Compare with', { exact: true }).selectOption('previous')
  await run.click()
  await section.getByText('3 messages receive copies. 2 need recipient review.', { exact: true }).waitFor()
  const previousDiff = await section.locator('summary').filter({ hasText: /^Folder diff/ }).innerText()
  assert.equal(previousDiff, 'Folder diff · 2')
  await section.getByLabel('Proof engine', { exact: true }).selectOption('gmail_backlog')
  await run.click()
  await section.getByText('0 messages receive copies. 2 need recipient review.', { exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/gmail-backlog.png`, fullPage: true })
  await section.getByLabel('Expected folder', { exact: true }).first().fill('INBOX')
  await section.getByLabel('Expected folder', { exact: true }).first().blur()
  await run.click()
  await section.getByRole('alert').filter({ hasText: 'Failing pins block this proof.' }).waitFor()
  await page.getByRole('button', { name: 'Add synthetic account', exact: true }).click()
  const scan = page.getByRole('button', { name: 'Run or resume account census', exact: true })
  await scan.waitFor()
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Run or resume account census' && !b.disabled))
  await scan.click()
  const open = page.getByRole('button', { name: 'Open saved census', exact: true })
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Open saved census' && !b.disabled))
  await open.click()
  const accountProof = page.locator('.accounts').getByRole('region', { name: 'Rules and proof', exact: true })
  await accountProof.getByRole('button', { name: 'Prove saved census', exact: true }).click()
  await accountProof.getByText('0 messages receive copies. 99 need recipient review.', { exact: true }).waitFor()
  assert.equal(await accountProof.locator('.decision').count(), 99)
  await page.screenshot({ path: `${artifacts}/saved-census-hold.png`, fullPage: true })
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('heading', { name: 'Regeln und Prüfung', exact: true }).first().waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/german-narrow.png`, fullPage: true })
  assert.deepEqual(errors, [])
  assert.deepEqual(await page.evaluate(() => window.rulesCspViolations), [])
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  console.log('PASS: built rules UI, 14 decisions, exact copy/review counts, omissions, artifact identity, baseline switch, Gmail no-forward, failing pin gate, saved-census conservative hold, German narrow layout, empty storage and CSP')
} finally { await browser.close() }
