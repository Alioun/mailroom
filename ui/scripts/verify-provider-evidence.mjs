import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'

const root = fileURLToPath(new URL('../../', import.meta.url))
const metadata = JSON.parse(await readFile(join(root, '.audit/provider-evidence-retained.json'), 'utf8'))
const artifacts = join(root, '.audit/provider-evidence-browser')
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = [], remote = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(metadata.base)) remote.push('Non-local request') })
  await page.addInitScript(() => {
    window.providerEvidenceCsp = []
    document.addEventListener('securitypolicyviolation', e => window.providerEvidenceCsp.push(e.violatedDirective))
  })
  await page.goto(new URL('/advanced.html', metadata.base).href)
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts select').first().selectOption(metadata.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  const evidence = page.locator('.accounts #account-overview > .acquisition-evidence')
  await evidence.getByText('Current Spam count', { exact: false }).waitFor()
  assert.match(await evidence.locator('.spam-observation').innerText(), /Observed 0.*STATUS MESSAGES/)
  await evidence.locator('summary').filter({ hasText: 'Last successful selected scan' }).click()
  await evidence.getByRole('heading', { name: 'Selected folders', exact: true }).waitFor()
  assert.match(await evidence.innerText(), /Archiv\/Grüße/)
  assert.match(await evidence.innerText(), /Not selectable. No count or headers requested./)
  assert.match(await evidence.innerText(), /not 12\/13-month coverage/)
  await page.screenshot({ path: join(artifacts, 'english-wire-observations.png'), fullPage: true })
  await page.getByRole('button', { name: 'Generate or refresh local report', exact: true }).click()
  await page.locator('.reports .acquisition-evidence .spam-observation').filter({ hasText: 'Observed 0' }).waitFor()
  await page.locator('.winddown > summary').click()
  await page.getByRole('button', { name: 'Open or refresh wind-down report', exact: true }).click()
  await page.locator('.winddown').getByText('Source versions and coverage', { exact: true }).click()
  assert.match(await page.locator('.winddown').innerText(), /STATUS MESSAGES/)
  assert.match(await page.locator('.winddown').innerText(), /historical|history/i)
  await writeFile(join(metadata.directory, 'provider-mode'), 'partial_list')
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.locator('.accounts [aria-live=polite]').getByText('Account action failed', { exact: true }).waitFor({ timeout: 30000 })
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await evidence.getByText('Older successful observations.', { exact: false }).waitFor()
  assert.match(await evidence.locator('.spam-observation').innerText(), /Unknown.*No current successful observation/)
  await page.screenshot({ path: join(artifacts, 'failed-refresh-keeps-older-facts.png'), fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts select').first().selectOption(metadata.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await evidence.getByText('Older successful observations.', { exact: false }).waitFor()
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await evidence.getByRole('heading', { name: 'Lokale Erfassungsbelege', exact: true }).waitFor()
  assert.match(await evidence.locator('.spam-observation').innerText(), /Unbekannt/)
  await writeFile(join(metadata.directory, 'provider-mode'), 'zero')
  await page.getByRole('button', { name: 'Kontoerfassung starten oder fortsetzen', exact: true }).click()
  await page.locator('.accounts [aria-live=polite]').getByText('Kontoaktion abgeschlossen', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Gespeicherte Erfassung öffnen', exact: true }).click()
  assert.match(await evidence.locator('.spam-observation').innerText(), /Beobachtet 0.*STATUS MESSAGES/)
  await evidence.locator('summary').filter({ hasText: 'Letzte erfolgreiche Erfassung' }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: join(artifacts, 'german-current-zero.png'), fullPage: true })
  assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage), csp: window.providerEvidenceCsp })), { local: [], session: [], csp: [] })
  assert.deepEqual(errors, [])
  assert.deepEqual(remote, [])
  const output = { ...metadata, checks: 8, built_ui: true, wire_derived: true, failed_refresh: true, reload: true, english_german: true, narrow: true, csp_storage_requests: true }
  await writeFile(join(root, '.audit/provider-evidence-browser-output.json'), JSON.stringify(output, null, 2) + '\n')
  console.log('PASS: 8 built-browser checks for wire-derived counts/topology, local reports/wind-down, failed refresh, reload, English/German, narrow layout, CSP and empty browser storage')
} finally { await browser.close() }
