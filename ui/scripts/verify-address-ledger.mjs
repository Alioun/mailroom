import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'
const root = fileURLToPath(new URL('../../', import.meta.url))
const artifacts = join(root, '.audit/address-ledger-browser')
await mkdir(artifacts, { recursive: true })
const retained = JSON.parse(await readFile(join(root, '.audit/address-ledger-retained.json'), 'utf8'))
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = [], urls = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => urls.push(request.url()))
  await page.addInitScript(() => {
    window.ledgerCspViolations = []
    document.addEventListener('securitypolicyviolation', event => window.ledgerCspViolations.push(event.violatedDirective))
  })
  await page.goto('http://127.0.0.1:4173')
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(retained.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await page.locator('.accounts .rules-proof').getByText('Saved workspace loaded.', { exact: true }).waitFor()
  const region = page.locator('.accounts .ledger')
  await region.locator(':scope > summary').click()
  const loadResponse = page.waitForResponse(r => r.url().endsWith('/api/accounts/ledger') && r.request().postDataJSON().command.action === 'open')
  await region.getByRole('button', { name: 'Reload ledger and reconcile', exact: true }).click()
  const initial = await (await loadResponse).json()
  await region.getByText('Ledger loaded from the private file.', { exact: true }).waitFor()
  await region.getByText('A new first_seen proposal is the time this review generated the proposal. It is not Message Date, first receipt or first census observation. Existing supplied values are preserved.', { exact: true }).waitFor()
  assert.ok(await region.getByText('Unknown', { exact: false }).count() > 0)
  const saved = region.getByRole('article').filter({ hasText: 'interrupted@signup.example.test' })
  await saved.getByRole('button', { name: 'Add to exact batch interrupted@signup.example.test', exact: true }).click()
  const form = region.locator('fieldset').filter({ hasText: 'interrupted@signup.example.test' })
  assert.equal(await form.getByLabel('first_seen value', { exact: true }).getAttribute('readonly'), '')
  await form.getByLabel('Private note', { exact: true }).fill('BROWSER-PRIVATE-LEDGER-NOTE')
  await form.getByLabel('Filing status', { exact: true }).selectOption('retired')
  const previewResponse = page.waitForResponse(r => r.url().endsWith('/api/accounts/ledger') && r.request().postDataJSON().command.action === 'preview')
  await region.getByRole('button', { name: 'Review exact ledger batch', exact: true }).click()
  const review = await (await previewResponse).json()
  assert.equal(review.batch.entries[0].note, 'BROWSER-PRIVATE-LEDGER-NOTE')
  assert.equal(review.batch.entries[0].status, 'retired')
  const save = region.getByRole('button', { name: 'Save confirmed ledger batch', exact: true })
  await save.waitFor()
  assert.equal(await save.isEnabled(), false)
  const confirmation = region.getByRole('checkbox', { name: 'I approve exactly this local ledger batch and its displayed effects', exact: true })
  await confirmation.check()
  await region.locator('.ledger-review').screenshot({ path: join(artifacts, 'exact-review.png') })
  await save.click()
  await region.getByText('Authoritative file saved and projection reconciled. Reload rules and run fresh proof.', { exact: true }).waitFor()
  assert.equal(await region.locator('.ledger-review').count(), 0)
  await region.getByRole('button', { name: 'Reload ledger and reconcile', exact: true }).click()
  await region.getByText('Ledger loaded from the private file.', { exact: true }).waitFor()
  await region.getByText('BROWSER-PRIVATE-LEDGER-NOTE', { exact: true }).waitFor()
  await region.screenshot({ path: join(artifacts, 'saved-and-leaks.png') })
  const proposal = initial.proposals.find(p => !['invoices@work.example.test', 'retired@signup.example.test'].includes(p.address))
  assert.ok(proposal)
  const addProposal = region.getByRole('button', { name: `Add to exact batch ${proposal.address}`, exact: true })
  await region.getByText(`${proposal.address} · Unknown`, { exact: true }).click()
  await addProposal.click()
  const proposalForm = region.locator('fieldset').filter({ hasText: proposal.address })
  assert.equal(await proposalForm.getByLabel('Service chosen by you', { exact: true }).inputValue(), '')
  assert.equal(await proposalForm.getByLabel('Folder leaf beneath the classified root', { exact: true }).inputValue(), '')
  await proposalForm.getByLabel('Service chosen by you', { exact: true }).fill('Browser explicitly reviewed service')
  await proposalForm.getByLabel('Folder leaf beneath the classified root', { exact: true }).fill('Review')
  await proposalForm.getByLabel('Private note', { exact: true }).fill('PROPOSAL-PRIVATE-NOTE')
  const proposalReviewResponse = page.waitForResponse(r => r.url().endsWith('/api/accounts/ledger') && r.request().postDataJSON().command.action === 'preview')
  await region.getByRole('button', { name: 'Review exact ledger batch', exact: true }).click()
  const proposalReview = await (await proposalReviewResponse).json()
  assert.match(proposalReview.batch.entries[0].first_seen_meaning, /not first receipt/)
  assert.equal(proposalReview.batch.entries[0].invoice, false)
  assert.equal(proposalReview.batch.entries[0].association, null)
  await confirmation.check(); await save.click()
  await region.getByText('Authoritative file saved and projection reconciled. Reload rules and run fresh proof.', { exact: true }).waitFor()
  const proofRegion = page.locator('.accounts .rules-proof')
  await proofRegion.getByRole('button', { name: 'Reload saved rules and pins', exact: true }).click()
  await proofRegion.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  const proofResponse = page.waitForResponse(r => r.url().endsWith('/api/accounts/proof/preview'))
  await proofRegion.getByRole('button', { name: 'Prove saved census', exact: true }).click()
  const proof = await (await proofResponse).json()
  assert.equal(proof.proof.artifact.context.recipient_evidence, 'unknown')
  assert.equal(proof.proof.counts.copies, 0)
  const proofConfirm = proofRegion.getByRole('checkbox', { name: 'I confirm this proof for a local Sieve download', exact: true })
  await proofConfirm.check()
  const fileView = await page.evaluate(async account => {
    const { token } = await fetch('/api/session').then(r => r.json())
    return fetch('/api/accounts/ledger', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Mailroom-Token': token }, body: JSON.stringify({ account, command: { action: 'open' } }) }).then(r => r.json())
  }, retained.account)
  fileView.snapshot.document.entries[0].note = 'EXTERNAL-BROWSER-PROOF-INVALIDATION'
  await writeFile(join(retained.directory, 'ledger/addresses.yaml'), JSON.stringify(fileView.snapshot.document))
  await proofRegion.getByRole('button', { name: 'Download confirmed Sieve', exact: true }).click()
  await proofRegion.getByText('Download rejected. Saved state changed or the gate blocks. Reload and review a fresh proof.', { exact: true }).waitFor()
  assert.equal(await proofRegion.getByRole('button', { name: 'Download confirmed Sieve', exact: true }).count(), 0)
  await region.getByRole('button', { name: 'Reload ledger and reconcile', exact: true }).click()
  await region.getByText('EXTERNAL-BROWSER-PROOF-INVALIDATION', { exact: true }).waitFor()
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await region.getByText('Erweitert · Privates Adressverzeichnis', { exact: true }).waitFor()
  await region.getByRole('button', { name: 'Adressverzeichnis laden und abgleichen', exact: true }).click()
  await region.getByText('Adressverzeichnis aus privater Datei geladen.', { exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await region.getByRole('button', { name: 'Zum genauen Stapel hinzufügen interrupted@signup.example.test', exact: true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await region.screenshot({ path: join(artifacts, 'german-narrow.png') })
  const storage = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage }, csp: window.ledgerCspViolations }))
  for (const marker of ['BROWSER-PRIVATE-LEDGER-NOTE', 'SYNTHETIC-LEDGER-PRIVATE-SERVICE', 'interrupted@signup.example.test', 'PROPOSAL-PRIVATE-NOTE']) {
    assert.equal(JSON.stringify(storage).includes(marker), false)
    assert.equal(urls.some(url => url.includes(marker)), false)
  }
  assert.deepEqual(storage.csp, [])
  assert.deepEqual(errors, [])
  console.log('PASS built English/German ledger review, private note/status save, exact confirmation, durable reload, leak signals, fresh proof, external edit denial without manual refresh, narrow viewport, CSP, URLs and browser-storage privacy')
} finally { await browser.close() }
