import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
const artifacts = fileURLToPath(new URL('../../.audit/durable-browser/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, acceptDownloads: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    window.durableCspViolations = []
    document.addEventListener('securitypolicyviolation', event => window.durableCspViolations.push(event.violatedDirective))
  })
  await page.goto('http://127.0.0.1:4173')
  await page.getByRole('button', { name: 'Add synthetic account', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  const region = page.locator('.accounts .rules-proof')
  const save = () => region.getByRole('button', { name: 'Save rules and pins encrypted', exact: true })
  const run = () => region.getByRole('button', { name: 'Prove saved census', exact: true })
  await save().click()
  await region.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  await region.getByText('Rule documents', { exact: true }).click()
  const overrides = region.getByLabel('Override YAML', { exact: true })
  const original = await overrides.inputValue()
  const marked = original.replace('folder: Studio', 'folder: Prüfung') + '\n# synthetic browser durable marker\n'
  await overrides.fill(marked)
  assert.equal(await run().isEnabled(), false)
  await save().click()
  await region.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  const selectedId = await page.locator('.accounts > .census-actions select').inputValue()
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(selectedId)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await region.getByText('Rule documents', { exact: true }).click()
  assert.equal(await overrides.inputValue(), marked)
  await run().click()
  await region.getByText('0 messages receive copies. 99 need recipient review.', { exact: true }).waitFor()
  await region.locator('.decision').first().getByRole('button', { name: 'Pin expected folder', exact: true }).click()
  assert.equal(await region.getByLabel('Expected folder', { exact: true }).count(), 1)
  await save().click()
  await region.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  await region.getByRole('button', { name: 'Reload saved rules and pins', exact: true }).click()
  await region.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  assert.equal(await region.getByLabel('Expected folder', { exact: true }).inputValue(), 'INBOX')
  await region.getByLabel('Expected folder', { exact: true }).fill('Synthetic/Wrong')
  await region.getByLabel('Expected folder', { exact: true }).blur()
  await save().click()
  await region.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  await run().click()
  await region.getByText('Failing pins block this proof.', { exact: true }).waitFor()
  assert.equal(await region.getByRole('button', { name: 'Download confirmed Sieve', exact: true }).count(), 0)
  await region.getByLabel('Expected folder', { exact: true }).fill('INBOX')
  await region.getByLabel('Expected folder', { exact: true }).blur()
  await save().click()
  await region.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  const response = page.waitForResponse(r => r.url().endsWith('/api/accounts/proof/preview'))
  await run().click()
  const proof = await (await response).json()
  const confirm = region.getByRole('checkbox', { name: 'I confirm this proof for a local Sieve download', exact: true })
  const downloadButton = region.getByRole('button', { name: 'Download confirmed Sieve', exact: true })
  await confirm.waitFor()
  assert.equal(await downloadButton.isEnabled(), false)
  await confirm.check()
  await region.locator('.local-download').screenshot({ path: `${artifacts}/confirmed-proof.png` })
  const downloadEvent = page.waitForEvent('download')
  await downloadButton.click()
  const download = await downloadEvent
  assert.equal(download.suggestedFilename(), 'rules.sieve')
  const chunks = []
  for await (const chunk of await download.createReadStream()) chunks.push(chunk)
  assert.deepEqual(Buffer.concat(chunks), Buffer.from(proof.proof.artifact.executable, 'utf8'))
  assert.deepEqual(proof.proof.artifact.folders, [])
  await region.getByText('Local download prepared and export baseline recorded. Provider application is unverified.', { exact: true }).waitFor()
  await region.locator('.workspace-controls').screenshot({ path: `${artifacts}/export-recorded.png` })
  const baselineResponse = page.waitForResponse(r => r.url().endsWith('/api/accounts/proof/preview'))
  await region.getByRole('button', { name: 'Compare with last recorded export', exact: true }).click()
  const baselineProof = await (await baselineResponse).json()
  assert.equal(baselineProof.previous.identity, proof.proof.artifact.identity)
  // A separate authorized synthetic scan changes persisted state without destroying the displayed proof.
  const result = await page.evaluate(async () => {
    const { token } = await (await fetch('/api/session')).json()
    const post = async (path, body) => (await fetch('/api/accounts/' + path, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Mailroom-Token': token }, body: JSON.stringify(body) })).json()
    const accounts = await post('list', {})
    const selected = document.querySelector('.accounts select').value
    const account = accounts.find(a => a.id === selected)
    await post('scan', { account: account.id })
    const deadline = Date.now() + 30000
    while (Date.now() < deadline) {
      const state = await (await fetch('/api/accounts/status', { headers: { 'X-Mailroom-Token': token } })).json()
      if (state.job.progress.state !== 'running') return state.job.progress.state
      await new Promise(resolve => setTimeout(resolve, 40))
    }
    return 'timeout'
  })
  assert.equal(result, 'complete')
  await confirm.check()
  await downloadButton.click()
  await region.getByText('Download rejected. Saved state changed or the gate blocks. Reload and review a fresh proof.', { exact: true }).waitFor()
  assert.equal(await downloadButton.count(), 0)
  await region.getByRole('button', { name: 'Reload saved rules and pins', exact: true }).click()
  await region.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  await overrides.fill('[')
  await save().click()
  await region.getByText('Save rejected. Invalid input or saved state changed. Reload before saving again.', { exact: true }).waitFor()
  await region.getByRole('button', { name: 'Reload saved rules and pins', exact: true }).click()
  await region.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  assert.equal(await overrides.inputValue(), marked)
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await region.locator('.workspace-controls').screenshot({ path: `${artifacts}/german-narrow.png` })
  assert.deepEqual(errors, [])
  assert.deepEqual(await page.evaluate(() => window.durableCspViolations), [])
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  console.log('PASS: built durable UI encrypted save/reload, durable pin editing, failing gate, explicit confirmation, exact downloaded Sieve, recorded previous baseline, stale scan rejection, malformed YAML recovery, narrow German layout, empty browser storage and CSP')
} finally { await browser.close() }
