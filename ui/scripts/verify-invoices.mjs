import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
const artifacts = fileURLToPath(new URL('../../.audit/invoice-browser/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => { window.invoiceCsp = []; document.addEventListener('securitypolicyviolation', event => window.invoiceCsp.push(event.violatedDirective)) })
  await page.goto('http://127.0.0.1:4173')
  const retained = JSON.parse(await readFile(fileURLToPath(new URL('../../.audit/invoice-retained.json', import.meta.url)), 'utf8'))
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(retained.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  let region = page.locator('.accounts .invoices')
  await region.locator('[data-invoice-status]').filter({ hasText: 'completed' }).waitFor()
  await region.screenshot({ path: `${artifacts}/restart-reconciled.png` })
  await page.getByRole('button', { name: 'Add synthetic account', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  const rules = page.locator('.accounts .rules-proof')
  await rules.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  await region.getByText('No current report rows. Save a rule workspace first.', { exact: true }).waitFor()
  await rules.getByText('Rule documents', { exact: true }).click()
  const override = rules.getByRole('textbox', { name: 'Override YAML', exact: true })
  await override.fill((await override.inputValue()).replace('home.example.test: personal', 'home.example.test: business').replace('- address: invoices@work.example.test', '- address: team@home.example.test'))
  await rules.getByRole('button', { name: 'Save rules and pins encrypted', exact: true }).click()
  await rules.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  await region.getByRole('button', { name: 'Refresh invoice report', exact: true }).click()
  await region.getByText('Business candidates · 7 · Unresolved role or evidence · 0', { exact: true }).waitFor()
  assert.equal(await region.locator('article').count(), 7)
  await region.locator('article').first().getByText('Predicted copies · accounting · Matching copy rules · forward.invoice_address', { exact: true }).waitFor()
  await region.getByRole('button', { name: 'Prepare mail-app forwarding', exact: true }).first().click()
  await region.getByText(/Preparation only. Nothing launched./).waitFor()
  assert.equal(await region.getByRole('checkbox').count(), 0)
  await region.screenshot({ path: `${artifacts}/native-preparation-only.png` })
  await region.getByRole('button', { name: 'Preview exact invoice', exact: true }).first().click()
  const confirmation = region.getByRole('checkbox', { name: 'Confirm this named synthetic send', exact: true })
  const send = region.getByRole('button', { name: 'Send exactly this invoice synthetically', exact: true })
  assert.equal(await confirmation.isChecked(), false)
  assert.equal(await send.isEnabled(), false)
  const exact = await region.locator('[data-invoice-preview] pre').textContent()
  assert.ok(exact.includes('SYNTHETIC-INVOICE-PRIVATE-BYTES'))
  await region.locator('[data-invoice-preview]').screenshot({ path: `${artifacts}/exact-source-target-sender.png` })
  await confirmation.check()
  const account = await page.locator('.accounts > .census-actions select').inputValue()
  await page.evaluate(async account => {
    const { token } = await fetch('/api/session').then(r => r.json())
    const headers = { 'Content-Type': 'application/json', 'X-Mailroom-Token': token }
    const saved = await fetch('/api/accounts/workspace/open', { method: 'POST', headers, body: JSON.stringify({ account }) }).then(r => r.json())
    const response = await fetch('/api/accounts/workspace/save', { method: 'POST', headers, body: JSON.stringify({ account, revision: saved.revision, input: saved.workspace.input }) })
    if (!response.ok) throw new Error('Synthetic stale-state setup failed')
  }, account)
  await send.click()
  await region.getByRole('alert').filter({ hasText: 'Invoice action rejected' }).waitFor()
  await region.getByRole('button', { name: 'Refresh invoice report', exact: true }).click()
  await region.getByRole('button', { name: 'Preview exact invoice', exact: true }).first().click()
  assert.equal(await confirmation.isChecked(), false)
  await confirmation.check(); await send.click()
  await region.locator('[data-invoice-status]').filter({ hasText: 'completed' }).waitFor()
  await region.screenshot({ path: `${artifacts}/completed-synthetic-send.png` })
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await region.locator('[data-invoice-status]').filter({ hasText: 'completed' }).waitFor()
  assert.equal(await confirmation.count(), 0)
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await region.getByRole('button', { name: 'Rechnungsbericht aktualisieren', exact: true }).click()
  await region.screenshot({ path: `${artifacts}/german-narrow.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  assert.deepEqual(await page.evaluate(() => window.invoiceCsp), [])
  assert.deepEqual(errors, [])
  console.log('PASS built invoice UI report badge, exact MIME preview, named synthetic confirmation, changed-state rejection, fallback preparation, send outcome, reload, actual replaced-process recovery, German narrow layout, empty browser storage and CSP')
} finally { await browser.close() }
