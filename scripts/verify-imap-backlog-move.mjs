import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fixture, root } from './imap-backlog-fixture.mjs'
const f = await fixture()
const options = { scope: 'inbox', protect_flagged: true, selected: null }
const checks = []
try {
  await f.start(true)
  const proof = await f.savedWorkspace(true, true)
  const preview = await f.command('preview', { options })
  assert.equal(preview.operation.plan.filing.artifact.identity, proof.proof.artifact.identity)
  assert.equal(preview.operation.plan.filing.artifact.executable, proof.proof.artifact.executable)
  assert.equal(preview.operation.plan.saved_proof, proof.receipt)
  assert.equal(preview.execution.baseline, 'previous')
  assert.equal(preview.execution.pins[0].status, 'pass')
  assert.deepEqual(preview.execution.pins[0].expected, proof.proof.pins[0].expected)
  assert.notEqual(preview.operation.plan.execution_proof, proof.receipt)
  assert.equal(preview.operation.plan.filing.changes.length, 3)
  const before = await f.observe()
  await f.command('confirm', { options, receipt: preview.receipt, confirmed: true })
  const job = await f.terminal()
  assert.equal(job.progress.state, 'complete')
  const current = await f.command('status')
  const run = current.journal.runs.at(-1)
  assert.equal(run.status, 'complete')
  assert.equal(run.batches[0].attempted, true)
  assert.equal(run.batches[0].mapping.kind, 'validated')
  const after = await f.observe()
  assert.equal(after.schema, 15)
  assert.deepEqual(after.folders.INBOX.uids, [99])
  assert.deepEqual(after.folders['Personal/Studio'].uids, [40,60,64,68])
  assert.ok(after.folders.INBOX.messages['99'].flags.includes('\\Deleted'))
  assert.equal(after.unrelated, before.unrelated)
  assert.equal(after.independent, before.independent)
  await f.stop('SIGKILL'); await f.start()
  assert.equal((await f.command('status')).journal.runs.at(-1).status, 'complete')
  await f.observe('later_flag')
  const undo = await f.command('undo_preview', { run: run.id })
  assert.equal(undo.reverse.length, 1)
  await f.command('undo', { run: run.id, receipt: undo.receipt, confirmed: true })
  assert.equal((await f.terminal()).progress.state, 'complete')
  const restored = await f.observe()
  assert.equal(restored.journal.runs.at(-1).status, 'undone')
  assert.deepEqual(restored.folders.INBOX.uids, [99,104,108,112])
  assert.ok(restored.folders.INBOX.messages['104'].flags.includes('$later-client'))
  assert.deepEqual(restored.folders['Personal/Studio'].uids, [40])
  assert.equal(restored.unrelated, before.unrelated)
  assert.equal(restored.independent, before.independent)
  assert.equal(await readFile(join(f.directory, 'move-wire-observations'), 'utf8'), 'UID MOVE\nUID MOVE\n')
  checks.push({ name: 'saved-proof-forward-reopen-reverse', passed: true, directory: f.directory, artifact: proof.proof.artifact.identity })
  await writeFile(join(root, '.audit/imap-backlog-workflow-http-results.json'), JSON.stringify({ checks }, null, 2))
  await f.close()
  for (const boundary of ['move_consumed', 'move_before_intent', 'move_attempted', 'move_provider_effect', 'move_parsed_mapping', 'move_saved_mapping', 'move_completion', 'move_readback', 'move_saved_readback']) {
    await f.start(true)
    await f.savedWorkspace()
    const preview = await f.command('preview', { options })
    const initial = await f.observe()
    await writeFile(join(f.directory, 'move-boundary'), boundary)
    await f.command('confirm', { options, receipt: preview.receipt, confirmed: true })
    await f.reached(boundary)
    await f.stop('SIGKILL')
    await writeFile(join(f.directory, 'move-boundary'), '')
    const independent = await f.observe()
    await f.start()
    const reopened = await f.command('status')
    const run = reopened.journal.runs.at(-1)
    const effectCount = (await readFile(join(f.directory, 'move-wire-exact.jsonl'), 'utf8').catch(() => '')).trim().split('\n').filter(Boolean).length
    assert.deepEqual((await f.observe()).folders, independent.folders)
    await f.command('reconcile', { run: run.id })
    const first = await f.observe()
    await f.command('reconcile', { run: run.id })
    const second = await f.observe()
    assert.equal(second.revision, first.revision)
    assert.equal(second.unrelated, initial.unrelated)
    assert.equal(second.independent, initial.independent)
    const mapped = ['move_saved_mapping','move_completion','move_readback','move_saved_readback'].includes(boundary)
    const safe = ['move_consumed','move_before_intent'].includes(boundary)
    assert.equal(second.journal.runs.at(-1).status, mapped ? 'complete' : safe ? 'stopped' : 'uncertain')
    if (!mapped && !safe) {
      await f.command('resume', { run: run.id }); await f.terminal()
      assert.equal((await f.observe()).journal.runs.at(-1).status, 'uncertain')
    }
    assert.equal((await readFile(join(f.directory, 'move-wire-exact.jsonl'), 'utf8').catch(() => '')).trim().split('\n').filter(Boolean).length, effectCount)
    checks.push({ name: 'actual-SIGKILL', boundary, directory: f.directory, effectCount, mapped, safe })
    await f.close()
  }
  await f.start(true, true, { large: true })
  await f.savedWorkspace()
  const large = await f.command('preview', { options })
  assert.equal(large.operation.plan.filing.changes.length, 501)
  assert.equal(Object.keys(large.operation.batches[0].intent.messages).length, 500)
  assert.equal(Object.keys(large.operation.batches[1].intent.messages).length, 1)
  await writeFile(join(f.directory, 'move-boundary'), 'move_between_batches')
  await f.command('confirm', { options, receipt: large.receipt, confirmed: true })
  await f.reached('move_between_batches')
  const cancelled = f.command('cancel')
  await new Promise(r => setTimeout(r, 100))
  await writeFile(join(f.directory, 'continue-move_between_batches'), 'continue')
  await cancelled
  const stopped = await f.observe()
  assert.equal(stopped.journal.runs.at(-1).status, 'stopped')
  assert.equal(stopped.journal.runs.at(-1).batches[1].attempted, false)
  assert.equal(stopped.journal.runs.at(-1).undo_receipt, null)
  await f.stop('SIGKILL'); await f.start()
  const retained = (await f.command('status')).journal.runs.at(-1)
  assert.equal(retained.status, 'stopped')
  await f.command('resume', { run: retained.id }); await f.terminal()
  assert.equal((await f.command('status')).journal.runs.at(-1).status, 'complete')
  assert.equal((await readFile(join(f.directory, 'move-wire-exact.jsonl'), 'utf8')).trim().split('\n').length, 2)
  checks.push({ name: '501-Cancel-replacement-explicit-remainder-Resume', passed: true, directory: f.directory })
  await writeFile(join(root, '.audit/imap-backlog-workflow-http-results.json'), JSON.stringify({ checks }, null, 2))
  console.log(`Passed ${checks.length} saved HTTP/TLS workflow groups`)

} finally { await f.close() }
