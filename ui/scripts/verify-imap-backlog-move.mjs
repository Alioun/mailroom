import assert from 'node:assert/strict'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { chromium } from 'playwright'
import { fixture, root, base, pause } from '../../scripts/imap-backlog-fixture.mjs'

async function undoDeadline(panel, german) {
  const line = panel.locator('.undo-deadline').first()
  await line.getByText(german ? /^Rückgängigmachen möglich bis .+\.$/ : /^Undo available until .+\.$/).waitFor()
  const until = Number(await line.getAttribute('data-undo-until'))
  assert.ok(Math.abs(until - (Date.now() / 1000 + 90 * 86400)) < 86400, 'Undo deadline is 90 days after completion')
}
const f = await fixture()
const artifacts = join(root, '.audit/imap-backlog-workflow-browser', new Date().toISOString().replace(/[:.]/g, '-'))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors = [], external = [], checks = []
let page
try {
  await f.start(true)
  page = await browser.newPage({ viewport: { width: 1280, height: 960 }, acceptDownloads: true })
  page.setDefaultTimeout(30000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(base)) external.push(request.url()) })
  await page.addInitScript(() => { window.moveCsp = []; document.addEventListener('securitypolicyviolation', event => window.moveCsp.push(event.violatedDirective)) })
  const rules = page.locator('.accounts .rules-proof')
  const panel = page.locator('.protocol-backlog')
  async function open(german = false) {
    await page.goto(base)
    await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
    await page.locator('.accounts > .census-actions select').selectOption(f.account)
    await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
    await rules.getByText('Saved workspace loaded.', { exact: true }).waitFor()
    await panel.waitFor()
    await page.waitForLoadState('networkidle')
    if (german) await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  }
  async function preview(german = false) {
    const [response] = await Promise.all([
      page.waitForResponse(r => r.url().endsWith('/api/accounts/backlog/protocol') && r.request().postDataJSON().command.action === 'preview'),
      panel.getByRole('button', { name: german ? 'Genaue Protokolländerungen anzeigen' : 'Preview exact protocol changes', exact: true }).click(),
    ])
    assert.equal(response.status(), 200)
    const value = await response.json()
    await panel.getByText(value.operation.plan.filing.artifact.identity, { exact: true }).waitFor()
    const approval = panel.getByRole('checkbox', { name: german ? 'Ich bestätige diese genauen UID-MOVE-Änderungen' : 'I confirm these exact UID MOVE changes', exact: true })
    assert.equal(await approval.isChecked(), false)
    return { value, approval }
  }
  await open()
  await rules.getByText('Rule documents', { exact: true }).click()
  const overrides = rules.getByLabel('Override YAML', { exact: true })
  await overrides.fill(`${await overrides.inputValue()}\n# saved through the built MOVE workflow\n`)
  await rules.getByRole('button', { name: 'Save rules and pins encrypted', exact: true }).click()
  await rules.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  const proofPending = page.waitForResponse(r => r.url().endsWith('/api/accounts/proof/preview'))
  await rules.getByRole('button', { name: 'Prove saved census', exact: true }).click()
  const proof = await (await proofPending).json()
  const downloadApproval = rules.getByRole('checkbox', { name: 'I confirm this proof for a local Sieve download', exact: true })
  assert.equal(await downloadApproval.isChecked(), false)
  await downloadApproval.check()
  const downloading = page.waitForEvent('download')
  await rules.getByRole('button', { name: 'Download confirmed Sieve', exact: true }).click()
  assert.equal(await readFile(await (await downloading).path(), 'utf8'), proof.proof.artifact.executable)
  await rules.getByText('Local download prepared and export baseline recorded. Provider application is unverified.', { exact: true }).waitFor()
  await rules.getByRole('button', { name: 'Compare with last recorded export', exact: true }).click()
  await rules.locator('.decision').first().waitFor()
  const superseded = await preview()
  await superseded.approval.check()
  await overrides.fill(`${await overrides.inputValue()}\n# invalidate the checked protocol approval\n`)
  await superseded.approval.waitFor({ state: 'detached' })
  await rules.getByRole('button', { name: 'Save rules and pins encrypted', exact: true }).click()
  await rules.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  const review = await preview()
  assert.equal(review.value.execution.baseline, 'previous')
  assert.equal(review.value.operation.plan.filing.artifact.identity, proof.proof.artifact.identity)
  assert.equal(review.value.operation.plan.filing.artifact.executable, proof.proof.artifact.executable)
  assert.equal(await panel.getByRole('button', { name: 'File this reviewed list', exact: true }).isEnabled(), false)
  await page.screenshot({ path: join(artifacts, 'english-preview.png'), fullPage: true })
  await panel.screenshot({ path: join(artifacts, 'english-preview-detail.png') })
  await review.approval.check()
  await panel.getByRole('button', { name: 'File this reviewed list', exact: true }).click()
  await panel.locator('[data-run-status="complete"]').waitFor()
  assert.deepEqual((await f.observe()).folders.INBOX.uids, [99])
  await undoDeadline(panel, false)
  await f.stop('SIGKILL'); await f.start()
  await open(true)
  await undoDeadline(panel, true)
  await panel.getByRole('button', { name: 'Bedingtes Rückgängigmachen prüfen', exact: true }).click()
  const undoApproval = panel.getByRole('checkbox', { name: 'Ich bestätige diese genauen umgekehrten UID-MOVE-Änderungen', exact: true })
  assert.equal(await undoApproval.isChecked(), false)
  await undoApproval.check()
  await panel.getByRole('button', { name: 'Geeignete Protokolländerungen rückgängig machen', exact: true }).click()
  await panel.locator('[data-run-status="undone"]').waitFor()
  await panel.locator('.undo-deadline').getByText(/^Rückgängig gemacht\. Das Journal bleibt bis .+ erhalten und wird dann durch eine Zusammenfassung ersetzt\.$/).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: join(artifacts, 'german-reverse.png'), fullPage: true })
  await panel.screenshot({ path: join(artifacts, 'german-reverse-detail.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length, document.cookie]), [0,0,''])
  assert.deepEqual(await page.evaluate(() => window.moveCsp), [])
  assert.deepEqual(errors, [])
  assert.deepEqual(external, [])
  checks.push({ name: 'built-English-save-proof-download-Previous-preview-forward-SIGKILL-German-reverse', directory: f.directory, passed: true })
  await f.close()
  await f.start(true, true, { large: true })
  await f.savedWorkspace()
  await open()
  await writeFile(join(f.directory, 'move-boundary'), 'move_between_batches')
  const large = await preview()
  assert.equal(large.value.operation.plan.filing.changes.length, 501)
  await large.approval.check()
  await panel.getByRole('button', { name: 'File this reviewed list', exact: true }).click()
  await f.reached('move_between_batches')
  const cancel = panel.getByRole('button', { name: 'Cancel sorting', exact: true })
  assert.equal(await cancel.isEnabled(), true)
  await cancel.click()
  await writeFile(join(f.directory, 'continue-move_between_batches'), 'continue')
  await panel.locator('[data-run-status="stopped"]').waitFor()
  await page.waitForLoadState('networkidle')
  assert.equal((await f.observe()).journal.runs.at(-1).batches[1].attempted, false)
  await f.stop('SIGKILL'); await f.start()
  await open(true)
  await panel.getByRole('button', { name: 'Nur Beobachtungen abgleichen', exact: true }).click()
  await panel.locator('[data-run-status="stopped"]').waitFor()
  await panel.getByRole('button', { name: 'Nie versuchten Rest fortsetzen', exact: true }).click()
  await panel.locator('[data-run-status="complete"]').waitFor()
  assert.equal((await f.observe()).journal.runs.at(-1).undo_receipt, null)
  await panel.getByRole('button', { name: 'Bedingtes Rückgängigmachen prüfen', exact: true }).click()
  assert.equal(await panel.getByRole('checkbox', { name: 'Ich bestätige diese genauen umgekehrten UID-MOVE-Änderungen', exact: true }).isChecked(), false)
  await page.screenshot({ path: join(artifacts, 'german-stopped-resumed-501.png'), fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  checks.push({ name: 'built-live-Cancel-501-replacement-Reconcile-explicit-Resume-unchecked-Undo', directory: f.directory, passed: true })
  await writeFile(join(root, '.audit/imap-backlog-workflow-browser-results.json'), JSON.stringify({ checks, errors, external, artifacts }, null, 2))
  console.log(`Passed ${checks.length} built protocol workflow groups`)
} catch (error) {
  if (page) { await page.screenshot({ path: join(artifacts, `failure-${Date.now()}.png`), fullPage: true }); await writeFile(join(artifacts, `failure-${Date.now()}.txt`), await page.locator('body').innerText()) }
  throw error
} finally { await browser.close(); await f.close() }
