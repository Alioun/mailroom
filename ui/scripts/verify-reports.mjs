import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'

const artifacts = fileURLToPath(new URL('../../.audit/reports-browser/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, acceptDownloads: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    window.reportCspViolations = []
    document.addEventListener('securitypolicyviolation', event => window.reportCspViolations.push(event.violatedDirective))
  })
  await page.goto('http://127.0.0.1:4173')
  await page.getByText('Synthetic account verification.', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Add synthetic Gmail account', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await page.getByLabel('As of (UTC)', { exact: true }).fill('2026-10-25T00:00')
  await page.getByRole('button', { name: 'Generate or refresh local report', exact: true }).click()
  await page.getByText('Partial acquisition.', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await page.locator('.account-addresses').getByRole('checkbox', { name: 'Confirm own address owner@example.test', exact: true }).check()
  await page.waitForFunction(() => !document.querySelector('.account-addresses input')?.disabled)
  await page.getByLabel('As of (UTC)', { exact: true }).fill('2026-10-25T00:00')
  await page.getByRole('button', { name: 'Generate or refresh local report', exact: true }).click()
  await page.getByText('100 canonical messages · 99 received · 1 sent · 100 saved records', { exact: true }).waitFor()
  await page.getByText('alex@people.example · Person · 20', { exact: true }).click()
  await page.getByText('User wrote to sender: Yes', { exact: false }).waitFor()
  await page.getByText('Gmail arrivals by month', { exact: true }).click()
  await page.getByText('{"2026-10":99}', { exact: true }).waitFor()
  const candidates = page.locator('.approved-values input')
  assert.equal(await candidates.count(), 2)
  assert.equal(await candidates.nth(0).isChecked(), true)
  await candidates.nth(0).uncheck()
  await candidates.nth(1).uncheck()
  await page.getByRole('button', { name: 'Preview exact shared text', exact: true }).click()
  await page.locator('.summary-preview').waitFor()
  const privatePreview = await page.locator('.summary-preview').innerText()
  for (const value of ['shop.example', 'platform.example', 'Synthetic account header', 'owner@example.test', 'alex@people.example', 'synthetic-private-token', 'Synthetic label']) assert.equal(privatePreview.includes(value), false, value)
  assert.equal(await page.getByRole('button', { name: 'Export reviewed summary', exact: true }).isEnabled(), false)
  await page.getByRole('checkbox', { name: 'Allow clear domain shop.example', exact: true }).check()
  assert.equal(await page.locator('.summary-preview').count(), 0)
  await page.getByRole('button', { name: 'Preview exact shared text', exact: true }).click()
  await page.locator('.summary-preview').waitFor()
  const exactPreview = await page.locator('.summary-preview').innerText()
  assert.equal(exactPreview.includes('shop.example'), true)
  assert.equal(exactPreview.includes('platform.example'), false)
  await page.getByRole('checkbox', { name: 'I reviewed this exact summary and want to export it', exact: true }).check()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export reviewed summary', exact: true }).click()
  const download = await downloadEvent
  assert.equal(download.suggestedFilename(), 'census-summary.md')
  let exported = ''
  for await (const chunk of await download.createReadStream()) exported += chunk.toString('utf8')
  assert.equal(exported, exactPreview)
  await page.screenshot({ path: `${artifacts}/reviewed-export.png`, fullPage: true })
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('heading', { name: 'Lokaler Erfassungsbericht', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/german-narrow.png`, fullPage: true })
  assert.deepEqual(errors, [])
  assert.deepEqual(await page.evaluate(() => window.reportCspViolations), [])
  assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage) })), { local: [], session: [] })
  console.log('PASS: fake Gmail report, partial/complete counts, Sent correspondence, arrivals, reviewed domain selection, private preview, confirmation, exact downloaded Markdown, German narrow layout, CSP and empty browser storage')
} finally { await browser.close() }
