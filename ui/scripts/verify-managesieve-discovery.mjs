import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'

const root = fileURLToPath(new URL('../../', import.meta.url))
const metadata = JSON.parse(await readFile(join(root, '.audit/managesieve-retained.json'), 'utf8'))
const artifacts = join(root, '.audit/managesieve-browser')
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = [], remote = []
  page.on('pageerror', () => errors.push('Page error'))
  page.on('request', request => { if (!request.url().startsWith(metadata.base)) remote.push('Non-local request') })
  await page.addInitScript(() => {
    window.sieveCsp = []
    document.addEventListener('securitypolicyviolation', e => window.sieveCsp.push(e.violatedDirective))
  })
  await page.goto(metadata.base)
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(metadata.account)
  const sieve = page.locator('.accounts .account-setup > .sieve')
  await sieve.getByRole('button', { name: 'Open local Sieve evidence', exact: true }).click()
  await sieve.locator('h4').first().waitFor()
  assert.match(await sieve.innerText(), /Production ManageSieve installation is missing/)
  assert.match(await sieve.innerText(), /Open-Xchange/)
  await writeFile(join(metadata.directory, 'sieve-mode'), 'valid_text')
  await sieve.getByRole('button', { name: 'Discover installed test server', exact: true }).click()
  await sieve.getByRole('button', { name: 'Discover installed test server', exact: true }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => !document.querySelector('.sieve .actions button:nth-child(2)')?.disabled)
  await sieve.getByRole('heading', { name: 'Current in installed test context', exact: true }).waitFor()
  assert.match(await sieve.innerText(), /Authenticated Sieve capabilities/)
  assert.match(await sieve.innerText(), /SHA-256 [a-f0-9]{64}/)
  await page.screenshot({ path: join(artifacts, 'english-current.png'), fullPage: true })
  await sieve.getByRole('button', { name: 'Review exact private bytes', exact: true }).first().click()
  assert.equal(await sieve.locator('pre').count() > 0, true)
  assert.equal(await sieve.locator('pre').first().evaluate(el => el.textContent.includes('HEX')), true)
  assert.equal(await sieve.locator('pre').first().evaluate(el => el.textContent.includes('<img')), true)
  assert.equal(await sieve.locator('pre img, pre script').count(), 0)
  await sieve.getByRole('button', { name: 'Hide private bytes', exact: true }).first().click()
  await writeFile(join(metadata.directory, 'sieve-mode'), 'missing')
  await sieve.getByRole('button', { name: 'Discover installed test server', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.sieve .actions button:nth-child(2)')?.disabled)
  await sieve.getByRole('heading', { name: 'Historical observations', exact: true }).waitFor()
  assert.match(await sieve.innerText(), /failed.*missing/s)
  assert.equal(await sieve.locator('pre').count(), 0)
  await writeFile(join(metadata.directory, 'sieve-mode'), 'stall_read')
  await sieve.getByRole('button', { name: 'Discover installed test server', exact: true }).click()
  await sieve.getByRole('button', { name: 'Cancel Sieve discovery', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.sieve .actions button:nth-child(2)')?.disabled)
  assert.match(await sieve.innerText(), /cancelled/)
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(metadata.account)
  await sieve.getByRole('button', { name: 'Open local Sieve evidence', exact: true }).click()
  await sieve.getByRole('heading', { name: 'Historical observations', exact: true }).waitFor()
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await sieve.getByRole('heading', { name: 'Historische Beobachtungen', exact: true }).waitFor()
  await writeFile(join(metadata.directory, 'sieve-mode'), 'empty')
  await sieve.getByRole('button', { name: 'Installierten Testserver erfassen', exact: true }).click()
  await sieve.getByRole('heading', { name: 'Aktuell im installierten Testkontext', exact: true }).waitFor()
  assert.match(await sieve.innerText(), /Vollständige Liste enthält keine Skripte/)
  assert.match(await sieve.innerText(), /Kein aktives Skript zurückgegeben/)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: join(artifacts, 'german-empty-narrow.png'), fullPage: true })
  assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage), csp: window.sieveCsp })), { local: [], session: [], csp: [] })
  assert.deepEqual(errors, []); assert.deepEqual(remote, [])
  await writeFile(join(root, '.audit/managesieve-browser-output.json'), JSON.stringify({ ...metadata, built_ui: true, checks: ['actual TLS discovery', 'exact private byte review', 'failed refresh and old baseline', 'cancellation', 'encrypted reload', 'English/German and narrow viewport', 'zero versus missing', 'no remote requests, browser storage or CSP errors'] }, null, 2) + '\n')
  console.log('PASS: 8 built-browser ManageSieve groups with local TLS, private byte review, failed refresh, cancellation, reload, English/German and security boundaries')
} finally { await browser.close() }
