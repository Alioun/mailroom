import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
const artifacts = fileURLToPath(new URL('../../.audit/backlog-browser/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    window.backlogCspViolations = []
    document.addEventListener('securitypolicyviolation', event => window.backlogCspViolations.push(event.violatedDirective))
  })
  await page.goto('http://127.0.0.1:4173')
  const retained = await readFile(fileURLToPath(new URL('../../.audit/backlog-retained.json', import.meta.url)), 'utf8').then(JSON.parse, () => null)
  if (retained) {
    await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
    await page.locator('.accounts > .census-actions select').selectOption(retained.account)
    await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
    const recovered = page.locator('.accounts .backlog').locator(`[data-run="${retained.run}"]`)
    await recovered.getByText('completed · 40 / 40 applied · 40 restored · 0 conflicts', { exact: true }).waitFor()
    await recovered.screenshot({ path: `${artifacts}/restart-recovered.png` })
  }
  await page.getByRole('button', { name: 'Add synthetic account', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.getByText('Account action complete', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  const rules = page.locator('.accounts .rules-proof')
  await rules.getByText('Saved workspace loaded.', { exact: true }).waitFor()
  await rules.getByRole('button', { name: 'Save rules and pins encrypted', exact: true }).click()
  await rules.getByText('Rules and pins saved encrypted.', { exact: true }).waitFor()
  const account = await page.locator('.accounts > .census-actions select').inputValue()
  const region = page.locator('.accounts .backlog')
  await region.getByRole('button', { name: 'Preview exact backlog changes', exact: true }).click()
  await region.getByText('40 eligible changes · 27 unmatched · 0 need review', { exact: true }).waitFor()
  const confirmation = region.getByRole('checkbox', { name: 'I confirm these exact synthetic mailbox changes', exact: true })
  assert.equal(await confirmation.isChecked(), false)
  assert.equal(await region.getByRole('button', { name: 'Sort synthetic backlog', exact: true }).isEnabled(), false)
  await region.locator('.destination input').first().uncheck()
  await region.getByText('0 eligible changes · 27 unmatched · 0 need review', { exact: true }).waitFor()
  assert.equal(await confirmation.count(), 0)
  await region.locator('.destination input').first().check()
  await confirmation.waitFor()
  assert.equal(await confirmation.isChecked(), false)
  await region.screenshot({ path: `${artifacts}/exact-preview.png` })
  await confirmation.check()
  await region.getByRole('button', { name: 'Sort synthetic backlog', exact: true }).click()
  await region.locator('.run-state').filter({ hasText: 'completed · 40 / 40 applied' }).waitFor({ timeout: 60000 })
  await region.screenshot({ path: `${artifacts}/completed-run.png` })
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await region.locator('.run-state').filter({ hasText: 'completed · 40 / 40 applied' }).waitFor()
  assert.equal(await confirmation.count(), 0)
  await region.getByRole('button', { name: 'Preview conditional undo', exact: true }).click()
  await region.getByText('40 eligible for undo · 0 conflicts', { exact: true }).waitFor()
  const undoButton = region.getByRole('button', { name: 'Undo eligible synthetic changes', exact: true })
  assert.equal(await undoButton.isEnabled(), false)
  await region.getByRole('checkbox', { name: 'I confirm this conditional undo', exact: true }).check()
  await undoButton.click()
  await region.locator('.run-state').filter({ hasText: '40 restored · 0 conflicts' }).waitFor({ timeout: 60000 })
  await region.screenshot({ path: `${artifacts}/conditional-undo.png` })
  assert.equal(await region.getByRole('button', { name: /Cancel/ }).count(), 0)
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await region.getByRole('button', { name: 'Genaue Bestandsänderungen anzeigen', exact: true }).click()
  await region.getByText(/geeignete Änderungen/).waitFor()
  await region.screenshot({ path: `${artifacts}/german-narrow.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  assert.deepEqual(await page.evaluate(() => window.backlogCspViolations), [])
  assert.deepEqual(errors, [])
  console.log('PASS built backlog UI exact selection, explicit synthetic confirmation, persisted run reload, conditional undo confirmation/report, pending Cancel, German narrow layout, empty browser storage and CSP')
} finally { await browser.close() }
