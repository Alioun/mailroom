import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'
const root = fileURLToPath(new URL('../../', import.meta.url))
const retainedPath = join(root, '.audit/account-lifecycle-retained.json')
const retained = JSON.parse(await readFile(retainedPath, 'utf8'))
const artifacts = join(root, '.audit/account-lifecycle-browser')
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  page.setDefaultTimeout(30000)
  const errors = [], urls = [], actions = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { urls.push(r.url()); if (r.url().endsWith('/api/accounts/lifecycle')) actions.push(r.postDataJSON().action) })
  await page.addInitScript(() => { window.lifecycleCsp = []; document.addEventListener('securitypolicyviolation', e => window.lifecycleCsp.push(e.violatedDirective)) })
  await page.goto(retained.base)
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  const selector = page.locator('.accounts > .census-actions select')
  await selector.selectOption(retained.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await page.locator('.accounts .rules-proof').getByText('Saved workspace loaded.', { exact: true }).waitFor()
  const region = page.locator('.accounts .lifecycle')
  await region.locator(':scope > summary').click()
  const response = action => page.waitForResponse(r => r.url().endsWith('/api/accounts/lifecycle') && r.request().postDataJSON().action === action)
  await region.getByRole('button', { name: 'Refresh lifecycle recovery status', exact: true }).click()
  assert.equal(await region.getByLabel('Replacement password', { exact: true }).inputValue(), '')
  assert.equal(await region.getByRole('button', { name: 'Rotate local encryption key', exact: true }).isEnabled(), false)
  const beforePassword = JSON.parse(await readFile(join(retained.directory, 'config', `${retained.account}.json`), 'utf8'))
  await region.getByLabel('Replacement password', { exact: true }).fill('synthetic-browser-replacement-only')
  let pending = response('replace_password')
  await region.getByRole('button', { name: 'Replace local account password', exact: true }).click()
  assert.equal((await pending).status(), 200)
  await region.getByText('Local lifecycle change saved. Account previews were cleared.', { exact: true }).waitFor()
  assert.equal(await page.locator('.accounts .rules-proof').count(), 0)
  assert.equal(await region.getByLabel('Replacement password', { exact: true }).inputValue(), '')
  const beforeRotation = JSON.parse(await readFile(join(retained.directory, 'config', `${retained.account}.json`), 'utf8'))
  assert.notEqual(beforePassword.password_ref, beforeRotation.password_ref)
  assert.equal(beforePassword.local_secret_ref, beforeRotation.local_secret_ref)
  await region.getByLabel('I confirm local key rotation and invalidation of outstanding approvals', { exact: true }).check()
  pending = response('rotate')
  await region.getByRole('button', { name: 'Rotate local encryption key', exact: true }).click()
  assert.equal((await pending).status(), 200)
  await region.getByText('Local lifecycle change saved. Account previews were cleared.', { exact: true }).waitFor()
  assert.equal(await region.getByLabel('I confirm local key rotation and invalidation of outstanding approvals', { exact: true }).isChecked(), false)
  const afterRotation = JSON.parse(await readFile(join(retained.directory, 'config', `${retained.account}.json`), 'utf8'))
  assert.equal(afterRotation.generation, beforeRotation.generation + 1)
  pending = response('forget_preview')
  await region.getByRole('button', { name: 'Preview exact local forgetting', exact: true }).click()
  let preview = await (await pending).json()
  assert.equal(preview.account, retained.account)
  const forget = region.getByRole('button', { name: 'Forget exactly these local resources', exact: true })
  assert.equal(await forget.isEnabled(), false)
  assert.equal(await region.getByLabel('I confirm forgetting this exact account and the displayed local resources', { exact: true }).isChecked(), false)
  await region.getByText(preview.consequences.en, { exact: true }).waitFor()
  await page.evaluate(async account => {
    const { token } = await fetch('/api/session').then(r => r.json())
    const headers = { 'Content-Type': 'application/json', 'X-Mailroom-Token': token }
    const saved = await fetch('/api/accounts/workspace/open', { method: 'POST', headers, body: JSON.stringify({ account }) }).then(r => r.json())
    const response = await fetch('/api/accounts/workspace/save', { method: 'POST', headers, body: JSON.stringify({ account, revision: saved.revision, input: saved.workspace.input }) })
    if (!response.ok) throw Error('Synthetic stale-preview setup failed')
  }, retained.account)
  await region.getByLabel('I confirm forgetting this exact account and the displayed local resources', { exact: true }).check()
  pending = response('forget')
  await forget.click(); assert.equal((await pending).status(), 422)
  await region.getByRole('alert').waitFor(); assert.equal(await region.locator('.lifecycle-review').count(), 0)
  pending = response('forget_preview')
  await region.getByRole('button', { name: 'Preview exact local forgetting', exact: true }).click()
  preview = await (await pending).json()
  await region.getByLabel('I confirm forgetting this exact account and the displayed local resources', { exact: true }).check()
  await region.locator('.lifecycle-review').screenshot({ path: join(artifacts, 'english-exact-forget.png') })
  pending = response('forget')
  await forget.click(); assert.equal((await pending).status(), 200)
  await page.waitForFunction(account => ![...document.querySelectorAll('.accounts > .census-actions option')].some(o => o.value === account), retained.account)
  assert.equal(await page.locator('.accounts .rules-proof').count(), 0)
  assert.equal(await page.locator(`.unsubscribe [data-account="${retained.account}"]`).count(), 0)
  await page.getByRole('button', { name: 'Add synthetic account', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.accounts .scan-state')?.textContent === 'Account action complete')
  const germanAccount = await selector.inputValue()
  assert.ok(germanAccount && germanAccount !== retained.account)
  await page.getByRole('button', { name: 'Run or resume account census', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.accounts .scan-state')?.textContent === 'Account action complete')
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  if (!(await region.getAttribute('open'))) await region.locator(':scope > summary').click()
  await region.getByLabel('Neues Passwort', { exact: true }).fill('synthetic-german-replacement-only')
  pending = response('replace_password')
  await region.getByRole('button', { name: 'Lokales Kontopasswort ersetzen', exact: true }).click()
  assert.equal((await pending).status(), 200)
  await region.getByLabel('Ich bestätige den lokalen Schlüsselwechsel und die Entwertung offener Freigaben', { exact: true }).check()
  pending = response('rotate')
  await region.getByRole('button', { name: 'Lokalen Verschlüsselungsschlüssel wechseln', exact: true }).click()
  assert.equal((await pending).status(), 200)
  pending = response('forget_preview')
  await region.getByRole('button', { name: 'Genaues lokales Vergessen prüfen', exact: true }).click()
  const germanPreview = await (await pending).json()
  assert.equal(germanPreview.account, germanAccount)
  assert.equal(await region.getByRole('button', { name: 'Genau diese lokalen Ressourcen vergessen', exact: true }).isEnabled(), false)
  await region.screenshot({ path: join(artifacts, 'german-narrow.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await region.getByLabel('Ich bestätige das Vergessen genau dieses Kontos und der angezeigten lokalen Ressourcen', { exact: true }).check()
  pending = response('forget')
  await region.getByRole('button', { name: 'Genau diese lokalen Ressourcen vergessen', exact: true }).click()
  assert.equal((await pending).status(), 200)
  await page.getByRole('button', { name: 'Synthetisches Konto hinzufügen', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.accounts .scan-state')?.textContent === 'Kontoaktion abgeschlossen')
  retained.forgotten.push(retained.account, germanAccount)
  retained.account = await selector.inputValue()
  assert.ok(retained.account)
  await writeFile(retainedPath, JSON.stringify(retained, null, 2) + '\n')
  assert.deepEqual(errors, [])
  assert.deepEqual(await page.evaluate(() => window.lifecycleCsp), [])
  assert.ok(urls.every(url => url.startsWith(retained.base) || url.startsWith('data:')))
  assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0, 0])
  for (const action of ['status', 'replace_password', 'rotate', 'forget_preview', 'forget']) assert.ok(actions.includes(action))
  console.log('PASS built English/German password replacement, rotation, exact unchecked forgetting, stale denial, confirmed deletion, account/cache clearing, narrow layout, CSP, local URLs and empty browser storage')
} finally { await browser.close() }
