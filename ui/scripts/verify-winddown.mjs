import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'
const root = fileURLToPath(new URL('../../', import.meta.url))
const retained = JSON.parse(await readFile(join(root, '.audit/winddown-retained.json'), 'utf8'))
const artifacts = join(root, '.audit/winddown-browser')
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  page.setDefaultTimeout(30000)
  const errors = [], urls = [], actions = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', r => { urls.push(r.url()); if (r.url().endsWith('/api/accounts/winddown')) actions.push(r.postDataJSON().command.action) })
  await page.addInitScript(() => { window.winddownCsp = []; document.addEventListener('securitypolicyviolation', e => window.winddownCsp.push(e.violatedDirective)) })
  await page.goto(new URL('/advanced.html', retained.base).href)
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(retained.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await page.locator('.accounts .rules-proof').getByText('Saved workspace loaded.', { exact: true }).waitFor()
  const region = page.locator('.accounts .winddown')
  await region.locator(':scope > summary').click()
  await region.getByLabel('As of, UTC', { exact: true }).fill('2026-10-25T00:00')
  async function load() {
    const response = page.waitForResponse(r => r.url().endsWith('/api/accounts/winddown') && r.request().postDataJSON().command.action === 'open')
    await region.getByRole('button', { name: 'Open or refresh wind-down report', exact: true }).click()
    const r = await response; assert.equal(r.status(), 200); return r.json()
  }
  let view = await load()
  assert.ok(view.report.rows.some(r => r.status === 'moved'))
  assert.ok(view.report.rows.some(r => r.status === 'quiet'))
  await region.getByText('Spam coverage and its count are unknown, not zero.', { exact: false }).waitFor()
  assert.equal(await region.locator('a[href^="https:"]').count(), 0, 'Settings links are local text, never automatic navigation')
  async function saveReview(buttonName) {
    const response = page.waitForResponse(r => r.url().endsWith('/api/accounts/winddown') && r.request().postDataJSON().command.action === 'preview')
    await region.getByRole('button', { name: buttonName, exact: true }).click()
    const r = await response; assert.equal(r.status(), 200)
    const preview = await r.json()
    const save = region.getByRole('button', { name: 'Save confirmed local decision', exact: true })
    assert.equal(await save.isEnabled(), false)
    await region.getByRole('checkbox', { name: 'I approve exactly this local decision and its displayed consequences', exact: true }).check()
    await region.locator('.winddown-review').screenshot({ path: join(artifacts, 'exact-decision-review.png') })
    const reopened = page.waitForResponse(r => r.url().endsWith('/api/accounts/winddown') && r.request().postDataJSON().command.action === 'open')
    await save.click()
    const next = await reopened; assert.equal(next.status(), 200)
    assert.equal(await region.locator('.winddown-review').count(), 0)
    return { preview, view: await next.json() }
  }
  const designation = region.getByRole('checkbox', { name: 'Designate this account as winding down', exact: true })
  await designation.uncheck()
  let saved = await saveReview('Review designation and comparison sources')
  assert.equal(saved.view.report.settings.winding_down, false)
  await designation.check()
  await saveReview('Review designation and comparison sources')
  const comparison = region.getByRole('checkbox', { name: 'new@destination.example.test', exact: true })
  await comparison.uncheck()
  saved = await saveReview('Review designation and comparison sources')
  assert.equal(saved.view.report.sources.length, 1)
  assert.equal(saved.view.report.rows.find(r => r.sender === 'alex@people.example').status, 'waiting')
  await comparison.check()
  saved = await saveReview('Review designation and comparison sources')
  assert.equal(saved.view.report.rows.find(r => r.sender === 'alex@people.example').status, 'moved')
  const waiting = region.locator('.winddown-row').filter({ hasText: 'waiting@people.example' })
  await waiting.locator(':scope > summary').click()
  await waiting.getByRole('button', { name: 'Review undismissal', exact: true }).click()
  let save = region.getByRole('button', { name: 'Save confirmed local decision', exact: true })
  assert.equal(await save.isEnabled(), false)
  await region.getByRole('checkbox', { name: 'I approve exactly this local decision and its displayed consequences', exact: true }).check()
  await save.click()
  await waiting.getByRole('button', { name: 'Review dismissal', exact: true }).waitFor()
  saved = await saveReview('Review dismissal')
  assert.equal(saved.view.report.rows.find(r => r.sender === 'waiting@people.example').status, 'dismissed')
  await region.getByRole('button', { name: 'Prepare bulk handoff', exact: true }).click()
  await page.locator('.unsubscribe .handoff').waitFor()
  assert.ok(await page.locator('.unsubscribe .handoff-match').count() > 0)
  assert.equal(await page.locator('.unsubscribe input[type=checkbox]:checked').count(), 0)
  assert.ok((await page.locator('.unsubscribe .handoff-match').evaluateAll(rows => rows.map(row => row.getAttribute('data-account')))).every(account => account === retained.account))
  assert.equal(await page.locator('.unsubscribe [data-unsubscribe-preview]').count(), 0)
  view = await load()
  async function outputPreview(name) {
    const response = page.waitForResponse(r => r.url().endsWith('/api/accounts/winddown') && r.request().postDataJSON().command.action === 'export_preview')
    await region.getByRole('button', { name, exact: true }).click()
    const r = await response; assert.equal(r.status(), 200)
    const result = await r.json()
    assert.equal(await region.locator('.winddown-output pre').textContent(), result.text)
    assert.equal(await region.getByRole('button', { name: 'Download confirmed output', exact: true }).isEnabled(), false)
    return result
  }
  const local = await outputPreview('Preview private local file')
  assert.equal(local.text, view.terminal)
  await region.getByRole('checkbox', { name: 'I approve exactly these output bytes and this disclosure', exact: true }).check()
  let downloaded = page.waitForEvent('download')
  await region.getByRole('button', { name: 'Download confirmed output', exact: true }).click()
  let download = await downloaded
  assert.equal(await readFile(await download.path(), 'utf8'), local.text)
  await writeFile(join(artifacts, 'downloaded-local.txt'), local.text)
  let summary = await outputPreview('Preview agent summary')
  for (const value of ['waiting@people.example', 'new@destination.example.test', 'own.er@gmail.com', 'platform.example/settings']) assert.equal(summary.text.includes(value), false)
  await region.getByRole('checkbox', { name: 'I approve exactly these output bytes and this disclosure', exact: true }).check()
  const ledgerFile = join(retained.directory, 'ledger/addresses.yaml')
  await writeFile(ledgerFile, (await readFile(ledgerFile, 'utf8')) + '\n# browser synthetic edit invalidates disclosure without refresh\n')
  await region.getByRole('button', { name: 'Download confirmed output', exact: true }).click()
  await region.getByRole('alert').waitFor()
  assert.equal(await region.locator('.winddown-output').count(), 0)
  await load()
  summary = await outputPreview('Preview agent summary')
  await region.locator('.winddown-output').screenshot({ path: join(artifacts, 'summary-preview.png') })
  await region.getByRole('checkbox', { name: 'I approve exactly these output bytes and this disclosure', exact: true }).check()
  downloaded = page.waitForEvent('download')
  await region.getByRole('button', { name: 'Download confirmed output', exact: true }).click()
  download = await downloaded
  assert.equal(await readFile(await download.path(), 'utf8'), summary.text)
  await writeFile(join(artifacts, 'downloaded-summary.txt'), summary.text)
  await page.reload()
  await page.getByRole('button', { name: 'Load saved accounts', exact: true }).click()
  await page.locator('.accounts > .census-actions select').selectOption(retained.account)
  await page.getByRole('button', { name: 'Open saved census', exact: true }).click()
  await region.locator(':scope > summary').click()
  await region.getByLabel('As of, UTC', { exact: true }).fill('2026-10-25T00:00')
  view = await load()
  assert.equal(view.report.rows.find(r => r.sender === 'waiting@people.example').status, 'dismissed')
  assert.equal(await region.locator('.winddown-review').count(), 0)
  assert.equal(await region.locator('.winddown-output').count(), 0)
  await page.getByRole('radio', { name: 'Deutsch', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await region.getByRole('button', { name: 'Stilllegungsbericht öffnen oder aktualisieren', exact: true }).waitFor()
  await region.locator('.winddown-row').filter({ hasText: 'waiting@people.example' }).locator(':scope > summary').click()
  await region.getByRole('button', { name: 'Aufhebung prüfen', exact: true }).waitFor()
  await region.screenshot({ path: join(artifacts, 'german-narrow.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage), csp: window.winddownCsp })), { local: [], session: [], csp: [] })
  assert.deepEqual(errors, [])
  assert.ok(urls.every(url => url.startsWith(retained.base) || url.startsWith('blob:')))
  assert.ok(actions.includes('confirm') && actions.includes('export'))
  console.log('PASS actual built UI designation/comparison selection, explained statuses, dismissal/undismissal, separate exact byte downloads, external-edit rejection, durable reload, Q20 handoff without approval, German narrow layout, CSP, local URLs and empty browser storage')
} finally { await browser.close() }
